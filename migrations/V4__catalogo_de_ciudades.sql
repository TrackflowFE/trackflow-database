-- La ciudad de origen y destino era texto libre, así que "Bogotá", "Bogota" y
-- "Bogotá D.C." eran tres ciudades distintas para el sistema. Con eso no se puede
-- saber cuántos envíos van a una ciudad, ni determinar cobertura, ni evitar que un
-- error de digitación mande un paquete a ninguna parte.
--
-- Se introduce un catálogo de municipios con identificador propio. No se usa el
-- código DANE: solo aportaría al interoperar con facturación electrónica o con otra
-- transportadora, y obligaría a cargar y mantener correctos los 1.122 códigos
-- oficiales. La pareja nombre + departamento ya identifica el municipio sin
-- ambigüedad. Si más adelante hace falta, el código DANE entra como columna
-- nullable y única sin tocar nada de lo demás.
--
-- El envío guarda únicamente el identificador. Repetir nombre y departamento en el
-- envío sería una dependencia transitiva y rompería 3NF.

create table cities (
    id bigint generated by default as identity,
    name varchar(120) not null,
    department varchar(120) not null,
    primary key (id),
    constraint uk_cities_name_department unique (name, department)
);

-- El autocompletado busca por nombre.
create index idx_cities_name on cities (name);

