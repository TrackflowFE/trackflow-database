-- Hasta esta versión, un hub intermedio era "cualquier ciudad menos la de destino", así
-- que un envío Medellín → Bogotá podía pasar por Cartagena y el sistema lo aceptaba.
-- Faltaba el dato que dice qué ciudades están conectadas entre sí: la red de rutas.
--
-- Cada fila es un tramo directo que la operación recorre, en un sentido, con su
-- duración aproximada en horas por carretera. Con estos tramos la aplicación calcula la
-- ruta más corta (Dijkstra) desde donde está el paquete hasta su destino, y un hub solo
-- es válido si es la siguiente ciudad de esa ruta.
--
-- La red tiene dos capas, como la de una transportadora real:
--   - Troncales: camiones directos entre los cinco hubs principales (Medellín, Bogotá,
--     Cali, Barranquilla y Cartagena), que no paran en las ciudades del camino.
--   - Regionales: los corredores que conectan las demás ciudades con esos hubs y entre
--     sí, y cada municipio metropolitano con su ciudad núcleo.
--
-- Los tramos se siembran en los dos sentidos. La columna active permite cerrar un tramo
-- (una vía cerrada, una ruta suspendida) sin borrarlo; la ruta se recalcula en cada
-- consulta, así que el cambio aplica de inmediato.

create table logistics_route_legs (
    id bigint generated by default as identity,
    from_city_id bigint not null,
    to_city_id bigint not null,
    hours integer not null,
    active boolean not null default true,
    primary key (id),
    constraint fk_logistics_route_legs_from foreign key (from_city_id) references cities (id),
    constraint fk_logistics_route_legs_to foreign key (to_city_id) references cities (id),
    constraint uk_logistics_route_legs unique (from_city_id, to_city_id),
    constraint ck_logistics_route_legs_hours check (hours > 0),
    constraint ck_logistics_route_legs_distinct check (from_city_id <> to_city_id)
);

create index idx_logistics_route_legs_from on logistics_route_legs (from_city_id);

