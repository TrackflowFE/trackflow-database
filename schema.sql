
CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public;

COMMENT ON EXTENSION unaccent IS 'text search dictionary that removes accents';

CREATE TABLE public.auth_sessions (
    jti character varying(64) NOT NULL,
    username character varying(50) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    last_activity_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    closed_at timestamp(6) with time zone
);

CREATE TABLE public.auth_users (
    username character varying(50) NOT NULL,
    password_hash character varying(100) NOT NULL,
    roles character varying(100) NOT NULL,
    active boolean DEFAULT true NOT NULL,
    created_at timestamp(6) with time zone NOT NULL
);

CREATE TABLE public.cities (
    id bigint NOT NULL,
    name character varying(120) NOT NULL,
    department character varying(120) NOT NULL
);

ALTER TABLE public.cities ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.cities_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.logistics_centers (
    id bigint NOT NULL,
    name character varying(160) NOT NULL,
    type character varying(30) NOT NULL,
    city_id bigint NOT NULL,
    address character varying(255) NOT NULL,
    active boolean DEFAULT true NOT NULL
);

ALTER TABLE public.logistics_centers ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.logistics_centers_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.logistics_events (
    id bigint NOT NULL,
    event_id character varying(255) NOT NULL,
    tracking_number character varying(255) NOT NULL,
    type character varying(255) NOT NULL,
    point character varying(255) NOT NULL,
    notes character varying(255),
    registered_at timestamp(6) with time zone NOT NULL,
    occurred_at timestamp(6) with time zone NOT NULL,
    center_id bigint,
    city_name character varying(255),
    deliverer_name character varying(160),
    city_id bigint,
    next_stop_city_id bigint,
    next_stop_city character varying(255),
    planned_leg_hours integer
);

ALTER TABLE public.logistics_events ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.logistics_events_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.logistics_route_legs (
    id bigint NOT NULL,
    from_city_id bigint NOT NULL,
    to_city_id bigint NOT NULL,
    hours integer NOT NULL,
    active boolean DEFAULT true NOT NULL,
    CONSTRAINT ck_logistics_route_legs_distinct CHECK ((from_city_id <> to_city_id)),
    CONSTRAINT ck_logistics_route_legs_hours CHECK ((hours > 0))
);

ALTER TABLE public.logistics_route_legs ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.logistics_route_legs_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.logistics_tracked_shipments (
    tracking_number character varying(255) NOT NULL,
    registered_at timestamp(6) with time zone NOT NULL,
    origin_city_id bigint NOT NULL,
    destination_city_id bigint NOT NULL
);

CREATE TABLE public.reports_shipment_tracking (
    tracking_number character varying(255) NOT NULL,
    status character varying(255) NOT NULL,
    recipient_name character varying(255) NOT NULL,
    destination_city character varying(255) NOT NULL,
    registered_at timestamp(6) with time zone NOT NULL,
    last_movement_point character varying(255),
    last_movement_at timestamp(6) with time zone,
    destination_city_id bigint NOT NULL,
    sender_name character varying(255) NOT NULL,
    origin_city_id bigint NOT NULL,
    origin_city character varying(255) NOT NULL,
    recipient_address character varying(255) NOT NULL,
    last_movement_city_id bigint,
    last_movement_city character varying(255),
    next_stop_city character varying(255),
    planned_leg_hours integer
);

CREATE TABLE public.reports_shipment_transit (
    tracking_number character varying(255) NOT NULL,
    received_at timestamp(6) with time zone,
    dispatched_at timestamp(6) with time zone,
    arrived_at timestamp(6) with time zone,
    out_for_delivery_at timestamp(6) with time zone,
    delivered_at timestamp(6) with time zone
);

CREATE TABLE public.reports_shipment_volume (
    tracking_number character varying(255) NOT NULL,
    registered_at timestamp(6) with time zone NOT NULL,
    origin_city_id bigint NOT NULL,
    origin_city character varying(255) NOT NULL,
    entry_center_id bigint,
    entry_point character varying(255),
    entry_city character varying(255),
    received_at timestamp(6) with time zone,
    delivered_at timestamp(6) with time zone,
    entry_city_id bigint
);

CREATE TABLE public.shipments (
    id bigint NOT NULL,
    tracking_number character varying(255) NOT NULL,
    sender_full_name character varying(255) NOT NULL,
    sender_document_number character varying(255) NOT NULL,
    sender_phone character varying(255) NOT NULL,
    sender_address character varying(255) NOT NULL,
    recipient_full_name character varying(255) NOT NULL,
    recipient_document_number character varying(255) NOT NULL,
    recipient_phone character varying(255) NOT NULL,
    recipient_address character varying(255) NOT NULL,
    description character varying(255) NOT NULL,
    status character varying(255) NOT NULL,
    registered_at timestamp(6) with time zone NOT NULL,
    last_movement_point character varying(255),
    last_movement_at timestamp(6) with time zone,
    sender_document_type character varying(5) NOT NULL,
    recipient_document_type character varying(5) NOT NULL,
    sender_city_id bigint NOT NULL,
    recipient_city_id bigint NOT NULL,
    CONSTRAINT ck_shipments_recipient_document_type CHECK (((recipient_document_type)::text = ANY ((ARRAY['CC'::character varying, 'CE'::character varying, 'TI'::character varying, 'PP'::character varying, 'NIT'::character varying])::text[]))),
    CONSTRAINT ck_shipments_sender_document_type CHECK (((sender_document_type)::text = ANY ((ARRAY['CC'::character varying, 'CE'::character varying, 'TI'::character varying, 'PP'::character varying, 'NIT'::character varying])::text[])))
);

